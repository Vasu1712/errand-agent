"""The eval table (reports/eval_table.md) and its JSON twin (reports/eval_results.json), and the
concurrency stress table (reports/eval_stress.md), written from the results of a run. Nothing in
them is typed by hand."""

import json
from dataclasses import asdict
from pathlib import Path

from errand.eval.suite import ScenarioResult

AUTOMATIC = ("steps", "script")


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _notes(result: ScenarioResult) -> str:
    notes = []
    for check in result.checks:
        if not check.passed:
            notes.append(f"FAILED {check.check}: {check.actual}")
    for invariant in result.invariants:
        for violation in invariant.violations[:3]:
            notes.append(f"invariant {invariant.id}: {violation}")
        if len(invariant.violations) > 3:
            notes.append(f"invariant {invariant.id}: {len(invariant.violations) - 3} more")
    if result.drift:
        notes.append(f"{len(result.drift)} replayed model requests differ from the recording")
    held = sum(i.passed for i in result.invariants)
    stats = result.stats
    notes.append(
        f"{result.mode}; covers {', '.join(result.covers)}; invariants {held}/{len(result.invariants)}"
        f" ({sum(i.checked for i in result.invariants)} items checked); {stats['runs']} runs,"
        f" {stats['tool_calls']} tool calls, {stats['model_calls']} model calls,"
        f" {stats['decisions']} decisions"
    )
    return "; ".join(notes)


def table(results: list[ScenarioResult]) -> str:
    passed = sum(r.passed for r in results)
    lines = [
        "# Eval results",
        "",
        "Generated by `make eval` (`python -m errand.eval`) from the scenarios in",
        "[evals/scenarios/](../evals/scenarios). Do not edit: rerun it. Every scenario runs offline",
        "against a scripted or recorded model and decider, with network access blocked; each one's",
        "full trace is in `traces/eval/<scenario>.jsonl`. Expected and actual come from the checks",
        "below each scenario's steps, which read the ledger, approvals, memory, mock world, trace and",
        "context manifests, never reply wording. Every scenario is also held to the seven global",
        "invariants (second table).",
        "",
        f"**{passed} of {len(results)} scenarios pass.**",
        "",
        "| scenario | expected | actual | pass/fail | notes |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        own = [c for c in r.checks if c.check not in AUTOMATIC]
        expected = "; ".join(c.expected for c in own) + f"; invariants 1–{len(r.invariants)} hold"
        actual = "; ".join(c.actual for c in own) + (
            f"; invariants {sum(i.passed for i in r.invariants)}/{len(r.invariants)} hold"
        )
        lines.append(
            f"| `{r.name}`: {_cell(r.title)} | {_cell(expected)} | {_cell(actual)} |"
            f" {'pass' if r.passed else '**FAIL**'} | {_cell(_notes(r))} |"
        )
    if results:
        invariants = results[0].invariants
        lines += [
            "",
            "## Global invariants",
            "",
            *[f"{i.id}. {i.name}" for i in invariants],
            "",
            "Items checked per scenario (✗ marks a violation):",
            "",
            "| scenario | " + " | ".join(str(i.id) for i in invariants) + " |",
            "|---|" + "---|" * len(invariants),
        ]
        for r in results:
            cells = [f"{'✓' if i.passed else '✗'} {i.checked}" for i in r.invariants]
            lines.append(f"| `{r.name}` | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def write_reports(results: list[ScenarioResult], reports_dir: Path) -> tuple[Path, Path]:
    reports_dir.mkdir(parents=True, exist_ok=True)
    md = reports_dir / "eval_table.md"
    md.write_text(table(results), encoding="utf-8")
    data = {
        "scenarios": len(results),
        "passed": sum(r.passed for r in results),
        "results": [
            {
                **{k: v for k, v in asdict(r).items() if k not in ("checks", "invariants")},
                "passed": r.passed,
                "checks": [asdict(c) for c in r.checks],
                "invariants": [{**asdict(i), "passed": i.passed} for i in r.invariants],
            }
            for r in results
        ],
    }
    out = reports_dir / "eval_results.json"
    out.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return md, out


def stress_table(results: dict[str, list[ScenarioResult]], seeds: list[int]) -> str:
    runs = sum(len(rs) for rs in results.values())
    passed = sum(r.passed for rs in results.values() for r in rs)
    lines = [
        "# Concurrency stress results",
        "",
        "Generated by `make eval-stress` (`python -m errand.eval --stress N`). Do not edit: rerun",
        "it. Each concurrency scenario is played once per world seed; the seed changes the",
        "catalogue, prices, open slots and random provider outcomes, and every run fires its turns",
        "on real threads through the ASGI app. Turnstiles pin only the interleaving a scenario is",
        "about. A run passes only if all its checks and all the global invariants hold. Traces are",
        "in `traces/eval/stress/<scenario>.seed<N>.jsonl`.",
        "",
        f"**{passed} of {runs} runs pass** ({len(results)} scenarios, seeds {seeds[0]}–{seeds[-1]}).",
        "",
        "| scenario | runs | passed | failed seeds | slowest run |",
        "|---|---|---|---|---|",
    ]
    for name, rs in results.items():
        failed = [str(seed) for seed, r in zip(seeds, rs, strict=True) if not r.passed]
        lines.append(
            f"| `{name}` | {len(rs)} | {sum(r.passed for r in rs)} | {', '.join(failed) or 'none'}"
            f" | {max(r.duration_s for r in rs)}s |"
        )
    return "\n".join(lines) + "\n"


def write_stress_report(
    results: dict[str, list[ScenarioResult]], seeds: list[int], reports_dir: Path
) -> Path:
    reports_dir.mkdir(parents=True, exist_ok=True)
    out = reports_dir / "eval_stress.md"
    out.write_text(stress_table(results, seeds), encoding="utf-8")
    return out
